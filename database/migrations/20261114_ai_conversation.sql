CREATE TABLE IF NOT EXISTS ai_conversation (
    id BIGINT NOT NULL AUTO_INCREMENT,
    conversation_id VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    scene VARCHAR(32) NOT NULL DEFAULT 'customer_service',
    status VARCHAR(16) NOT NULL DEFAULT 'open',
    last_message_at DATETIME DEFAULT NULL,
    last_channel VARCHAR(32) DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_conversation_user_scene (user_id, scene),
    UNIQUE KEY uk_ai_conversation_id (conversation_id),
    KEY idx_ai_conversation_user_updated (user_id, updated_at DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS ai_message (
    id BIGINT NOT NULL AUTO_INCREMENT,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    channel VARCHAR(32) NOT NULL,
    external_chat_id VARCHAR(128) DEFAULT NULL,
    external_message_id VARCHAR(128) DEFAULT NULL,
    client_message_id VARCHAR(128) NOT NULL,
    direction VARCHAR(16) NOT NULL,
    content_type VARCHAR(16) NOT NULL DEFAULT 'text',
    content LONGTEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'completed',
    sequence_no BIGINT NOT NULL,
    model_name VARCHAR(128) DEFAULT NULL,
    tools_used JSON DEFAULT NULL,
    error_code VARCHAR(64) DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_message_client (conversation_id, client_message_id),
    UNIQUE KEY uk_ai_message_external (channel, external_message_id, direction),
    KEY idx_ai_message_conversation_seq (conversation_id, sequence_no, id),
    KEY idx_ai_message_user_created (user_id, created_at),
    CONSTRAINT fk_ai_message_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversation(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS ai_drawing_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    drawing_id VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    conversation_id BIGINT DEFAULT NULL,
    message_id BIGINT DEFAULT NULL,
    prompt VARCHAR(4000) NOT NULL,
    model_name VARCHAR(128) DEFAULT NULL,
    provider VARCHAR(128) DEFAULT NULL,
    object_key VARCHAR(512) DEFAULT NULL,
    image_url VARCHAR(2000) DEFAULT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'generating',
    width INT DEFAULT NULL,
    height INT DEFAULT NULL,
    error_code VARCHAR(64) DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_drawing_id (drawing_id),
    KEY idx_ai_drawing_user_created (user_id, created_at DESC),
    CONSTRAINT fk_ai_drawing_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversation(id),
    CONSTRAINT fk_ai_drawing_message FOREIGN KEY (message_id) REFERENCES ai_message(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
